        Check(!new PetPlacement { Size = 80, CenterX = Double.NaN }.IsValid(), "invalid saved coordinates rejected");
        int undoCount = 0;
        UndoToast.ShowCompleted("긴 메모 내용이 있어도 되돌리기 버튼은 잘리지 않아야 합니다.\n두 번째 줄", delegate { undoCount++; }); Pump();
