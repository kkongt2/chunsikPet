using System;
using System.Reflection;
using System.Collections.Generic;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Threading;
using ChunsikDesktop;
internal static class GhostNoteTests {
    static int count;
    static void Check(bool ok, string name) { count++; if (!ok) throw new Exception("FAIL: " + name); }
    static T Field<T>(TodoNote note, string name) { return (T)typeof(TodoNote).GetField(name, BindingFlags.Instance | BindingFlags.NonPublic).GetValue(note); }
    static void Pump() { Application.Current.Dispatcher.Invoke(DispatcherPriority.ApplicationIdle, new Action(delegate {})); }
    [STAThread] public static void Main() {
        Application app = new Application { ShutdownMode = ShutdownMode.OnExplicitShutdown };
        TodoNote.LoadArt(System.IO.Path.GetFullPath("ChunsikDesktopPet"));
        typeof(PetWindow).GetMethod("LoadFrames", BindingFlags.Static | BindingFlags.NonPublic).Invoke(null, new object[] { System.IO.Path.GetFullPath("ChunsikDesktopPet/chunsik-sprites.png") });
        bool allowSave = true; int completed = 0, added = 0;
        TodoItem item = new TodoItem { Text = "원본" };
        TodoNote note = new TodoNote(delegate { completed++; }, delegate {}, delegate(double x, double y) {}, delegate { return allowSave; }, delegate { added++; });
        note.Update(item); note.Show(); Pump();
        Grid drag = Field<Grid>(note, "dragSurface");
        Border bar = Field<Border>(note, "dragBar");
        Image mascot = Field<Image>(note, "mascot");
        Check(!NativeNoteInput.IsClickThrough(note), "visible note always accepts body input");
        Check(Field<ScrollViewer>(note, "messageScroll").Opacity == 0.6 && note.Topmost, "memo is translucent and topmost");
        Check(mascot.Width == 43 && mascot.Height == 33, "top mascot is half size on each axis");
        Check(typeof(TodoNote).GetField("ghostHeader", BindingFlags.Instance | BindingFlags.NonPublic) == null, "edit move button removed");
        Check(drag.Cursor == System.Windows.Input.Cursors.SizeAll, "entire top region advertises dragging");
        Check(Object.ReferenceEquals(drag.InputHitTest(new Point(10, 8)), drag), "blank upper left is a drag target");
        Check(drag.InputHitTest(new Point(10, 35)) != null, "left side of visible bar is a drag target");
        Point petAt = mascot.TranslatePoint(new Point(), note), barAt = bar.TranslatePoint(new Point(), note);
        Check(petAt.Y < barAt.Y && petAt.Y + mascot.ActualHeight > barAt.Y, "pet peeks over wall with paws in front");
        double savedWidth = item.NoteWidth;
        item.NoteWidth = 220; note.Update(item); Pump();
        Check(Math.Abs(drag.ActualWidth - Field<Grid>(note, "root").ActualWidth) < 1, "drag strip spans minimum note width");
        Check(Field<Button>(note, "addNote").TranslatePoint(new Point(), note).Y >= bar.TranslatePoint(new Point(0, bar.ActualHeight), note).Y, "action buttons are below drag strip");
        Check(Field<ScrollViewer>(note, "messageScroll").ActualHeight >= 68, "minimum layout reserves text space");
        item.Peek = false; note.Update(item); Pump();
        Check(Field<ScrollViewer>(note, "messageScroll").ActualHeight >= 68, "bottom mascot layout reserves text space");
        item.Peek = true; note.Update(item); Pump();
        item.NoteWidth = savedWidth; note.Update(item); Pump();
        double savedHeight = item.NoteHeight;
        item.NoteHeight = 100; note.Update(item); Pump();
        double compactHeight = note.MinHeight;
        ScrollViewer body = Field<ScrollViewer>(note, "messageScroll");
        double lineHeight = Field<TextBlock>(note, "message").FontFamily.LineSpacing * item.FontSize;
        Check(compactHeight < 200 && body.ActualHeight >= lineHeight && body.ActualHeight < lineHeight + 12, "minimum height reserves approximately one text line");
        item.FontSize = 40; note.Update(item); Pump();
        Check(note.MinHeight > compactHeight, "minimum height follows note font size");
        item.FontSize = 17; item.NoteHeight = savedHeight; note.Update(item); Pump();
        item.NoteOpacity = 0.1; note.Update(item); Pump(); Check(Field<ScrollViewer>(note, "messageScroll").Opacity == 0.1, "10 percent opacity supported");
        item.NoteOpacity = 1; note.Update(item); Pump(); Check(note.Opacity == 1, "100 percent opacity supported");
        item.NoteOpacity = 0.6; note.Update(item); Pump();
        Button[] controls = new Button[] { Field<Button>(note, "addNote"), Field<Button>(note, "smaller"), Field<Button>(note, "larger"), Field<Button>(note, "completeButton"), Field<Button>(note, "moreTransparent"), Field<Button>(note, "lessTransparent"), Field<Button>(note, "minimizeButton") };
        foreach (Button control in controls) Check(control.IsVisible, "action button remains visible");
        Check(typeof(TodoNote).GetField("modeButton", BindingFlags.Instance | BindingFlags.NonPublic) == null, "click-through toggle removed");
        Check(controls[6].Content.ToString() == "▾ 접기" && controls[0].HorizontalAlignment == HorizontalAlignment.Left && controls[6].HorizontalAlignment == HorizontalAlignment.Right, "add and collapse have distinct labels and positions");
        controls[0].RaiseEvent(new RoutedEventArgs(Button.ClickEvent));
        Check(added == 1 && !note.IsEditing, "add works directly in normal mode");
        int font = item.FontSize;
        controls[1].RaiseEvent(new RoutedEventArgs(Button.ClickEvent));
        Check(item.FontSize == font - 2 && !note.IsEditing, "smaller works directly");
        controls[2].RaiseEvent(new RoutedEventArgs(Button.ClickEvent));
        Check(item.FontSize == font && !note.IsEditing, "larger works directly");
        controls[3].RaiseEvent(new RoutedEventArgs(Button.ClickEvent));
        Check(completed == 1 && !note.IsEditing, "complete works directly with one click");
        Check(controls[0].Content.ToString() == "＋ 메모" && controls[3].Content.ToString() == "✓", "compact add and complete icons");
        Check(typeof(TodoNote).GetField("fontLabel", BindingFlags.Instance | BindingFlags.NonPublic) == null, "font number removed");
        controls[4].RaiseEvent(new RoutedEventArgs(Button.ClickEvent));
        Check(item.NoteOpacity == 0.5 && Field<ScrollViewer>(note, "messageScroll").Opacity == 0.5 && !note.IsEditing, "opacity minus works directly");
        controls[5].RaiseEvent(new RoutedEventArgs(Button.ClickEvent));
        Check(item.NoteOpacity == 0.6 && Field<ScrollViewer>(note, "messageScroll").Opacity == 0.6, "opacity plus works directly");
        allowSave = false;
        controls[5].RaiseEvent(new RoutedEventArgs(Button.ClickEvent));
        Check(item.NoteOpacity == 0.6 && Field<ScrollViewer>(note, "messageScroll").Opacity == 0.6, "failed opacity save rolls back"); allowSave = true;
        item.NoteOpacity = 0.1; note.Update(item);
        controls[4].RaiseEvent(new RoutedEventArgs(Button.ClickEvent)); Check(item.NoteOpacity == 0.1 && !controls[4].IsEnabled, "opacity lower bound");
        item.NoteOpacity = 1; note.Update(item);
        controls[5].RaiseEvent(new RoutedEventArgs(Button.ClickEvent)); Check(item.NoteOpacity == 1 && !controls[5].IsEnabled, "opacity upper bound");
        item.NoteOpacity = 0.6; note.Update(item); Pump();
        double storedWidth = item.NoteWidth, storedHeight = item.NoteHeight;
        controls[6].RaiseEvent(new RoutedEventArgs(Button.ClickEvent)); Pump();
        GhostNoteHeader restore = Field<GhostNoteHeader>(note, "restoreTab");
        Check(((TextBlock)((Button)restore.Content).Content).Text.Contains("원본"), "minimized tab identifies memo");
        Check(item.Minimized && restore.IsVisible && NativeNoteInput.IsClickThrough(note), "minimized note exposes restore tab and passes body clicks");
        Check(Field<Grid>(note, "root").Visibility == Visibility.Hidden && !drag.IsVisible, "minimized hides paper and header");
        ((Button)restore.Content).RaiseEvent(new RoutedEventArgs(Button.ClickEvent)); Pump();
        Check(!item.Minimized && !restore.IsVisible && drag.IsVisible && item.NoteWidth == storedWidth && item.NoteHeight == storedHeight, "restore preserves note dimensions");
        allowSave = false;
        controls[6].RaiseEvent(new RoutedEventArgs(Button.ClickEvent)); Pump();
        Check(!item.Minimized && !restore.IsVisible, "failed minimize save remains visible"); allowSave = true;
        System.Windows.Controls.Primitives.Thumb resize = Field<System.Windows.Controls.Primitives.Thumb>(note, "grip");
        double width = note.Width;
        resize.RaiseEvent(new System.Windows.Controls.Primitives.DragStartedEventArgs(0, 0));
        resize.RaiseEvent(new System.Windows.Controls.Primitives.DragDeltaEventArgs(20, 10));
        resize.RaiseEvent(new System.Windows.Controls.Primitives.DragCompletedEventArgs(20, 10, false)); Pump();
        Check(note.Width == width + 20 && item.NoteWidth == note.Width && !NativeNoteInput.IsClickThrough(note), "direct resize persists size and keeps interactive body");
        note.BeginEdit(); Pump();
        Check(note.IsEditing && note.Opacity == 1 && !NativeNoteInput.IsClickThrough(note), "memo editing is opaque and interactive");
        Check(drag.IsVisible, "drag strip remains available during editing");
        Field<TextBox>(note, "inlineEditor").Text = "保存";
        controls[1].RaiseEvent(new RoutedEventArgs(Button.ClickEvent));
        Field<Button>(note, "lessTransparent").RaiseEvent(new RoutedEventArgs(Button.ClickEvent));
        Check(note.IsEditing && Field<TextBox>(note, "inlineEditor").Text == "保存" && item.Text == "원본", "appearance changes preserve unsaved edit");
        Field<Button>(note, "saveEditButton").RaiseEvent(new RoutedEventArgs(Button.ClickEvent)); Pump();
        Check(item.Text == "保存" && completed == 1, "save changes text without completing task");
        Check(!note.IsEditing && !NativeNoteInput.IsClickThrough(note) && drag.IsVisible, "save returns to normal mode");
        note.BeginEdit(); Field<TextBox>(note, "inlineEditor").Text = "discard";
        Field<Button>(note, "cancelEditButton").RaiseEvent(new RoutedEventArgs(Button.ClickEvent)); Pump();
        Check(item.Text == "保存" && !NativeNoteInput.IsClickThrough(note), "cancel preserves original and keeps body interactive");
        note.BeginEdit(); allowSave = false;
        Field<Button>(note, "saveEditButton").RaiseEvent(new RoutedEventArgs(Button.ClickEvent)); Pump();
        Check(note.IsEditing && !NativeNoteInput.IsClickThrough(note) && note.Opacity == 1, "failed save remains interactive");
        allowSave = true; note.FlushEdit(); Pump();
        double oldLeft = drag.PointToScreen(new Point()).X; note.Left += 50; Pump();
        Check(drag.PointToScreen(new Point()).X > oldLeft, "drag strip travels with note");
        note.Hide(); Pump(); Check(!drag.IsVisible, "strip hides with note");
        note.Show(); Pump(); Check(drag.IsVisible, "strip returns with note");
        note.DisposeNote(); Pump(); Check(!note.IsVisible, "note closes");
        PetOptions preferences = new PetOptions { PetCount = 2 };
        preferences.Placements.Add(new PetPlacement { Paused = true, Size = 50, CenterX = -400, BottomY = 1080 });
        preferences.Placements.Add(new PetPlacement { Size = 180, CenterX = 1500, BottomY = 900 });
        System.Xml.Serialization.XmlSerializer serializer = new System.Xml.Serialization.XmlSerializer(typeof(PetOptions));
        string xml;
        using (System.IO.StringWriter writer = new System.IO.StringWriter()) { serializer.Serialize(writer, preferences); xml = writer.ToString(); }
        PetOptions restored;
        using (System.IO.StringReader reader = new System.IO.StringReader(xml)) restored = (PetOptions)serializer.Deserialize(reader);
        Check(restored.PetCount == 2 && restored.Placements.Count == 2, "pet count and individual placements persist");
        Check(restored.Placements[0].Size == 50 && restored.Placements[0].CenterX == -400 && restored.Placements[1].Size == 180 && restored.Placements[1].BottomY == 900, "per-pet sizes and negative monitor coordinates survive reload");
        Check(restored.Placements[0].Paused && !restored.Placements[1].Paused, "individual resting and walking modes survive reload");
        PetOptions copy = restored.Copy(); copy.Placements[0].Size = 500;
        Check(restored.Placements[0].Size == 50, "settings copies do not mutate saved placement");
        using (System.IO.StringReader reader = new System.IO.StringReader("<PetOptions><PetCount>3</PetCount></PetOptions>")) restored = (PetOptions)serializer.Deserialize(reader);
        Check(restored.PetCount == 3 && restored.Placements.Count == 0 && PetPreferences.Valid(restored), "old count-only settings remain valid");
        using (System.IO.StringReader reader = new System.IO.StringReader("<PetOptions><Placements><PetPlacement><Size>80</Size><CenterX>100</CenterX><BottomY>800</BottomY></PetPlacement></Placements></PetOptions>")) restored = (PetOptions)serializer.Deserialize(reader);
        Check(!restored.Placements[0].Paused && restored.Placements[0].IsValid(), "legacy placement defaults to walking mode");
        Check(!new PetPlacement { Size = 80, CenterX = Double.NaN }.IsValid(), "invalid saved coordinates rejected");
        int undoCount = 0;
        UndoToast.ShowCompleted("긴 메모 내용이 있어도 되돌리기 버튼은 잘리지 않아야 합니다.\n두 번째 줄", delegate { undoCount++; }); Pump();
        UndoToast toast = (UndoToast)typeof(UndoToast).GetField("current", BindingFlags.Static | BindingFlags.NonPublic).GetValue(null);
        Button undoButton = (Button)typeof(UndoToast).GetField("undoButton", BindingFlags.Instance | BindingFlags.NonPublic).GetValue(toast);
        Point undoAt = undoButton.TranslatePoint(new Point(), toast);
        Check(toast.SizeToContent == SizeToContent.Height && undoButton.ActualHeight >= 38 && undoAt.Y + undoButton.ActualHeight <= toast.ActualHeight - 10, "undo action is fully visible in content-sized toast");
        undoButton.RaiseEvent(new RoutedEventArgs(Button.ClickEvent)); Pump();
        Check(undoCount == 1 && !toast.IsVisible, "undo action fires once and dismisses toast");
        Console.WriteLine("PASS: " + count + " normal mode assertions"); app.Shutdown();
    }
}
